//! Trace generation for the Blake round component.
//!
//! Row generation is embarrassingly parallel: every vec-row writes a disjoint
//! slot of each column. The trace columns are therefore split into contiguous
//! row chunks, each generated independently (one xor-multiplicity accumulator
//! per chunk, merged at the end).

